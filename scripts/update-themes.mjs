// Regenerates src/lib/theme-data.ts from Monkeytype's theme definitions.
//
//   node scripts/update-themes.mjs
//
// Monkeytype keeps the canonical color palettes in
// frontend/src/ts/constants/themes.ts. Themes that also ship a CSS override
// file (animations/gradients) are reduced to their base colors here.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const SOURCE =
  "https://raw.githubusercontent.com/monkeytypegame/monkeytype/master/frontend/src/ts/constants/themes.ts";

const FIELDS = [
  "bg",
  "main",
  "caret",
  "sub",
  "subAlt",
  "text",
  "error",
  "errorExtra",
  "colorfulError",
  "colorfulErrorExtra",
];

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "src", "lib", "theme-data.ts");

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`Fetch failed: ${response.status} ${response.statusText}`);
const source = await response.text();

const entryRe = /^ {2}"?([\w-]+)"?: \{([\s\S]*?)^ {2}\},$/gm;
const fieldRe = /(\w+):\s*(?:"([^"]*)"|(true|false))/g;

const themes = [];
for (const match of source.matchAll(entryRe)) {
  const name = match[1];
  const body = match[2];
  const parsed = {};
  for (const field of body.matchAll(fieldRe)) {
    parsed[field[1]] = field[2] ?? field[3] === "true";
  }
  const missing = FIELDS.filter((f) => typeof parsed[f] !== "string");
  if (missing.length > 0) throw new Error(`${name}: missing fields ${missing.join(", ")}`);
  for (const f of FIELDS) {
    if (!/^#[0-9a-fA-F]{3,8}$/.test(parsed[f])) {
      throw new Error(`${name}.${f}: invalid color "${parsed[f]}"`);
    }
  }
  themes.push(Object.fromEntries(["name", ...FIELDS].map((key) => [key, key === "name" ? name : parsed[key]])));
}

if (themes.length < 100) {
  throw new Error(`Parsed only ${themes.length} themes - the upstream format probably changed.`);
}

const rows = themes
  .map((t) => `  { name: "${t.name}", ${FIELDS.map((f) => `${f}: "${t[f]}"`).join(", ")} },`)
  .join("\n");

const output = `// Generated by scripts/update-themes.mjs - do not edit by hand.
// Source: ${SOURCE}
// Fetched: ${new Date().toISOString().slice(0, 10)} (${themes.length} themes)

export interface ThemeData {
  name: string;
  bg: string;
  main: string;
  caret: string;
  sub: string;
  subAlt: string;
  text: string;
  error: string;
  errorExtra: string;
  colorfulError: string;
  colorfulErrorExtra: string;
}

export const THEME_DATA: ThemeData[] = [
${rows}
];
`;

await writeFile(outFile, output);
console.log(`Wrote ${themes.length} themes to ${path.relative(root, outFile)}`);
