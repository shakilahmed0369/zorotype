// Regenerates the bundled keyboard library from keymap-editor-contrib.
//
//   npm run boards:update
//
// The library (https://github.com/nickcoutsos/keymap-editor-contrib, ISC) holds
// community-maintained layout data in the QMK info.json shape: one entry per key with its
// matrix row/col and its visual x/y, ordered to match the keyboard's ZMK matrix transform.
// That is exactly what the importer needs, so boards can be offered without the user
// hand-loading a layout file.
import { writeFile } from "node:fs/promises";

const BASE = "https://raw.githubusercontent.com/nickcoutsos/keymap-editor-contrib/main";
const HEADER = `// Generated by scripts/update-boards.mjs — do not edit by hand.
// Layout data from keymap-editor-contrib (https://github.com/nickcoutsos/keymap-editor-contrib, ISC).
`;

const res = await fetch(`${BASE}/keyboard-catalog.json`);
if (!res.ok) throw new Error(`catalog fetch failed: ${res.status}`);
const catalog = await res.json();

const ids = Object.keys(catalog).sort();
const catalogEntries = [];
const layouts = {};
const failures = [];

for (const id of ids) {
  try {
    const response = await fetch(`${BASE}/keyboard-data/${id}.json`);
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const data = await response.json();
    const layoutMap = data.layouts || {};
    const firstLayout = layoutMap[Object.keys(layoutMap)[0]];
    const keys = (firstLayout?.layout || []).map((k) => {
      const tuple = [k.row, k.col, k.x ?? 0, k.y ?? 0, k.w ?? 1, k.h ?? 1, k.r ?? 0, k.rx ?? 0, k.ry ?? 0];
      // Trim trailing defaults so the bundle stays compact: w/h default to 1, r/rx/ry to 0.
      while (tuple.length > 4 && tuple[tuple.length - 1] === (tuple.length === 5 || tuple.length === 6 ? 1 : 0)) {
        tuple.pop();
      }
      return tuple;
    });
    if (keys.length === 0) throw new Error("no keys");
    layouts[id] = keys;
    catalogEntries.push({ id, name: String(catalog[id].name || id) });
  } catch (err) {
    failures.push(`${id}: ${err.message}`);
  }
}

await writeFile(
  "src/lib/board-catalog.ts",
  `${HEADER}
export interface BoardCatalogEntry {
  id: string;
  name: string;
}

export const BOARD_CATALOG: BoardCatalogEntry[] = [
${catalogEntries.map((e) => `  { id: ${JSON.stringify(e.id)}, name: ${JSON.stringify(e.name)} },`).join("\n")}
];
`
);

await writeFile(
  "src/lib/board-data.ts",
  `${HEADER}
/** [row, col, x, y, w?, h?, r?, rx?, ry?] — w/h default to 1, r/rx/ry to 0. */
export type BoardKeyTuple = number[];

export const BOARD_LAYOUTS: Record<string, BoardKeyTuple[]> = {
${Object.entries(layouts)
  .map(([id, keys]) => `  ${JSON.stringify(id)}: [${keys.map((k) => `[${k.join(",")}]`).join(",")}],`)
  .join("\n")}
};
`
);

console.log(`wrote ${catalogEntries.length} boards to board-catalog.ts and board-data.ts`);
if (failures.length) console.log(`skipped (${failures.length}): ${failures.join(", ")}`);
